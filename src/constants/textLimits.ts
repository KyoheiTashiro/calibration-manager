/**
 * 自由文字列フィールドの文字数上限(単一の真実源)。
 * LocalStorage 容量(約5MB)の無制限消費を防ぐため、データの入口
 * (フォーム入力・CSVインポート)の両方でこの上限を適用する。
 *
 * なぜ src/domain/ に置かないか: UI/検証層の関心でありドメイン仕様ではないため。
 * 文字数は zod 標準 .max() と同じ UTF-16 コードユニットで数える
 * (サロゲートペアは2文字換算になるが、上限値に余裕があるため許容)。
 */
export const TEXT_LIMIT = {
  /** 管理番号・型式・シリアル番号・電話番号など識別子系 */
  code: 50,
  /** 機器名・氏名・名称・部署・設置場所・実施者など名称系 */
  name: 50,
  /** メールアドレス(RFC 5321 の 254 文字) */
  email: 254,
  /** 備考(note)系 */
  note: 500,
} as const;

/**
 * 電話番号は半角数字とハイフンのみ許容(空文字は各入力経路の optional 側で許容済み)。
 * 全角数字・スペース・`+`・`()` は不許可とし、入力者に半角統一を強制して表記ゆれを防ぐ。
 */
export const PHONE_PATTERN = /^[0-9-]+$/u;
